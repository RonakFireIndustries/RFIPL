-- ============================================================
-- RFIPL INVENTORY - PURCHASING & QUALITY CONTROL
-- MySQL 5.7+ (compatible with 5.7.23)
-- ------------------------------------------------------------
-- Step 3 of the inventory rebuild. Creates only:
--   1. purchase_requests
--   2. purchase_request_items
--   3. purchase_orders
--   4. purchase_order_items
--   5. goods_receipts
--   6. goods_receipt_items
--   7. quality_inspections
--
-- Depends on (already created):
--   HRMS: users, departments
--   Inventory: inventory_units, suppliers, raw_materials,
--              raw_material_batches, raw_material_stock,
--              raw_material_stock_ledger
--
-- DESIGN NOTES
--   * Two-stage approval:
--       Purchase request: draft -> pending_manager -> manager_approved
--       Purchase order:   draft -> pending_admin   -> approved
--   * Actor columns (requestedBy, receivedBy, inspectedBy and the
--     approval users) reference users(id), not employees(id). This lets
--     the admin account act even though it has no linked employee row.
--   * Single store: no stock_locations table and no locationId anywhere.
--   * Document numbers are generated by the backend (PR-0001, PO-0001,
--     GRN-0001) and stay unique here.
--   * Unit prices are entered manually; the backend may suggest a price
--     from the preferred supplier, but the schema does not enforce it.
--   * A saved QC inspection post approved quantity to raw_material_stock
--     and writes raw_material_stock_ledger rows (handled in the API).
--   * No seed rows.
--
-- Usage (phpMyAdmin: Import) or:
--   mysql -h <host> -u <user> -p <database> < inventory_purchasing_qc.sql
-- ============================================================

SET FOREIGN_KEY_CHECKS = 0;


-- ============================================================
-- 1. PURCHASE REQUESTS
-- ============================================================

CREATE TABLE IF NOT EXISTS purchase_requests (
    id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,

    -- Backend-generated: PR-0001, PR-0002, ...
    requestNumber VARCHAR(50) NOT NULL,

    departmentId BIGINT UNSIGNED NULL,

    -- users(id), not employees(id)
    requestedBy BIGINT UNSIGNED NOT NULL,

    requestDate DATE NOT NULL,
    requiredDate DATE NULL,

    purpose TEXT NULL,

    status ENUM(
        'draft',
        'pending_manager',
        'manager_approved',
        'rejected',
        'converted_to_po',
        'cancelled'
    ) NOT NULL DEFAULT 'draft',

    managerApprovedBy BIGINT UNSIGNED NULL,
    managerApprovedAt DATETIME NULL,
    managerRemarks TEXT NULL,

    createdAt TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updatedAt TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
        ON UPDATE CURRENT_TIMESTAMP,
    deletedAt DATETIME NULL,

    PRIMARY KEY (id),

    UNIQUE KEY uq_purchase_request_number (requestNumber),

    KEY idx_purchase_request_status (status),
    KEY idx_purchase_request_department (departmentId),
    KEY idx_purchase_request_requested_by (requestedBy),

    CONSTRAINT fk_purchase_request_department
        FOREIGN KEY (departmentId)
        REFERENCES departments(id)
        ON DELETE SET NULL,

    CONSTRAINT fk_purchase_request_requested_by
        FOREIGN KEY (requestedBy)
        REFERENCES users(id),

    CONSTRAINT fk_purchase_request_manager
        FOREIGN KEY (managerApprovedBy)
        REFERENCES users(id)
        ON DELETE SET NULL

) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4
COLLATE=utf8mb4_unicode_ci;


-- ============================================================
-- 2. PURCHASE REQUEST ITEMS
-- ============================================================

CREATE TABLE IF NOT EXISTS purchase_request_items (
    id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,

    purchaseRequestId BIGINT UNSIGNED NOT NULL,
    rawMaterialId BIGINT UNSIGNED NOT NULL,

    quantity DECIMAL(18,4) NOT NULL,
    unitId BIGINT UNSIGNED NOT NULL,

    remarks TEXT NULL,

    PRIMARY KEY (id),

    KEY idx_pr_item_request (purchaseRequestId),
    KEY idx_pr_item_material (rawMaterialId),

    CONSTRAINT fk_pr_item_request
        FOREIGN KEY (purchaseRequestId)
        REFERENCES purchase_requests(id)
        ON DELETE CASCADE,

    CONSTRAINT fk_pr_item_material
        FOREIGN KEY (rawMaterialId)
        REFERENCES raw_materials(id),

    CONSTRAINT fk_pr_item_unit
        FOREIGN KEY (unitId)
        REFERENCES inventory_units(id)

) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4
COLLATE=utf8mb4_unicode_ci;


-- ============================================================
-- 3. PURCHASE ORDERS
-- ============================================================

CREATE TABLE IF NOT EXISTS purchase_orders (
    id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,

    -- Backend-generated: PO-0001, PO-0002, ...
    poNumber VARCHAR(50) NOT NULL,

    purchaseRequestId BIGINT UNSIGNED NULL,
    supplierId BIGINT UNSIGNED NOT NULL,

    orderDate DATE NOT NULL,
    expectedDeliveryDate DATE NULL,

    totalAmount DECIMAL(14,2) NOT NULL DEFAULT 0,

    status ENUM(
        'draft',
        'pending_admin',
        'approved',
        'rejected',
        'partially_received',
        'received',
        'cancelled'
    ) NOT NULL DEFAULT 'draft',

    -- users(id)
    createdBy BIGINT UNSIGNED NOT NULL,

    adminApprovedBy BIGINT UNSIGNED NULL,
    adminApprovedAt DATETIME NULL,
    adminRemarks TEXT NULL,

    createdAt TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updatedAt TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
        ON UPDATE CURRENT_TIMESTAMP,
    deletedAt DATETIME NULL,

    PRIMARY KEY (id),

    UNIQUE KEY uq_purchase_order_number (poNumber),

    KEY idx_purchase_order_status (status),
    KEY idx_purchase_order_supplier (supplierId),
    KEY idx_purchase_order_request (purchaseRequestId),

    CONSTRAINT fk_purchase_order_request
        FOREIGN KEY (purchaseRequestId)
        REFERENCES purchase_requests(id)
        ON DELETE SET NULL,

    CONSTRAINT fk_purchase_order_supplier
        FOREIGN KEY (supplierId)
        REFERENCES suppliers(id),

    CONSTRAINT fk_purchase_order_created_by
        FOREIGN KEY (createdBy)
        REFERENCES users(id),

    CONSTRAINT fk_purchase_order_admin
        FOREIGN KEY (adminApprovedBy)
        REFERENCES users(id)
        ON DELETE SET NULL

) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4
COLLATE=utf8mb4_unicode_ci;


-- ============================================================
-- 4. PURCHASE ORDER ITEMS
-- ============================================================

CREATE TABLE IF NOT EXISTS purchase_order_items (
    id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,

    purchaseOrderId BIGINT UNSIGNED NOT NULL,
    rawMaterialId BIGINT UNSIGNED NOT NULL,

    orderedQuantity DECIMAL(18,4) NOT NULL,
    receivedQuantity DECIMAL(18,4) NOT NULL DEFAULT 0,

    unitId BIGINT UNSIGNED NOT NULL,

    -- Entered manually (the API may only suggest a value)
    unitPrice DECIMAL(14,2) NOT NULL,
    totalAmount DECIMAL(14,2) NOT NULL,

    PRIMARY KEY (id),

    KEY idx_po_item_order (purchaseOrderId),
    KEY idx_po_item_material (rawMaterialId),

    CONSTRAINT fk_po_item_order
        FOREIGN KEY (purchaseOrderId)
        REFERENCES purchase_orders(id)
        ON DELETE CASCADE,

    CONSTRAINT fk_po_item_material
        FOREIGN KEY (rawMaterialId)
        REFERENCES raw_materials(id),

    CONSTRAINT fk_po_item_unit
        FOREIGN KEY (unitId)
        REFERENCES inventory_units(id)

) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4
COLLATE=utf8mb4_unicode_ci;


-- ============================================================
-- 5. GOODS RECEIPT NOTES (GRN)
-- ============================================================

CREATE TABLE IF NOT EXISTS goods_receipts (
    id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,

    -- Backend-generated: GRN-0001, GRN-0002, ...
    grnNumber VARCHAR(50) NOT NULL,

    purchaseOrderId BIGINT UNSIGNED NOT NULL,
    supplierId BIGINT UNSIGNED NOT NULL,

    receivedDate DATE NOT NULL,

    -- users(id)
    receivedBy BIGINT UNSIGNED NOT NULL,

    status ENUM(
        'received',
        'partially_qc',
        'qc_completed',
        'cancelled'
    ) NOT NULL DEFAULT 'received',

    remarks TEXT NULL,

    createdAt TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updatedAt TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
        ON UPDATE CURRENT_TIMESTAMP,

    PRIMARY KEY (id),

    UNIQUE KEY uq_grn_number (grnNumber),

    KEY idx_grn_purchase_order (purchaseOrderId),
    KEY idx_grn_supplier (supplierId),
    KEY idx_grn_status (status),

    CONSTRAINT fk_grn_purchase_order
        FOREIGN KEY (purchaseOrderId)
        REFERENCES purchase_orders(id),

    CONSTRAINT fk_grn_supplier
        FOREIGN KEY (supplierId)
        REFERENCES suppliers(id),

    CONSTRAINT fk_grn_received_by
        FOREIGN KEY (receivedBy)
        REFERENCES users(id)

) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4
COLLATE=utf8mb4_unicode_ci;


-- ============================================================
-- 6. GOODS RECEIPT ITEMS
-- Single store: no locationId column.
-- ============================================================

CREATE TABLE IF NOT EXISTS goods_receipt_items (
    id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,

    goodsReceiptId BIGINT UNSIGNED NOT NULL,
    purchaseOrderItemId BIGINT UNSIGNED NOT NULL,
    rawMaterialId BIGINT UNSIGNED NOT NULL,

    batchNumber VARCHAR(100) NOT NULL,

    receivedQuantity DECIMAL(18,4) NOT NULL,
    approvedQuantity DECIMAL(18,4) NOT NULL DEFAULT 0,
    rejectedQuantity DECIMAL(18,4) NOT NULL DEFAULT 0,

    unitId BIGINT UNSIGNED NOT NULL,

    -- Entered manually
    purchasePrice DECIMAL(14,2) NOT NULL,

    qcStatus ENUM(
        'pending',
        'approved',
        'partially_approved',
        'rejected'
    ) NOT NULL DEFAULT 'pending',

    createdAt TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,

    PRIMARY KEY (id),

    KEY idx_grn_material_batch (rawMaterialId, batchNumber),
    KEY idx_grn_item_grn (goodsReceiptId),
    KEY idx_grn_item_po_item (purchaseOrderItemId),
    KEY idx_grn_item_qc_status (qcStatus),

    CONSTRAINT fk_grn_item_grn
        FOREIGN KEY (goodsReceiptId)
        REFERENCES goods_receipts(id)
        ON DELETE CASCADE,

    CONSTRAINT fk_grn_item_po
        FOREIGN KEY (purchaseOrderItemId)
        REFERENCES purchase_order_items(id),

    CONSTRAINT fk_grn_item_material
        FOREIGN KEY (rawMaterialId)
        REFERENCES raw_materials(id),

    CONSTRAINT fk_grn_item_unit
        FOREIGN KEY (unitId)
        REFERENCES inventory_units(id)

) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4
COLLATE=utf8mb4_unicode_ci;


-- ============================================================
-- 7. QUALITY INSPECTIONS
-- Saving an inspection posts approved quantity to stock in the API.
-- ============================================================

CREATE TABLE IF NOT EXISTS quality_inspections (
    id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,

    goodsReceiptItemId BIGINT UNSIGNED NOT NULL,

    -- users(id)
    inspectedBy BIGINT UNSIGNED NOT NULL,
    inspectedAt DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,

    approvedQuantity DECIMAL(18,4) NOT NULL DEFAULT 0,
    rejectedQuantity DECIMAL(18,4) NOT NULL DEFAULT 0,

    status ENUM(
        'approved',
        'partially_approved',
        'rejected'
    ) NOT NULL,

    remarks TEXT NULL,

    rejectionAction ENUM(
        'return_supplier',
        'rejected_stock'
    ) NULL,

    createdAt TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,

    PRIMARY KEY (id),

    KEY idx_qc_grn_item (goodsReceiptItemId),
    KEY idx_qc_status (status),
    KEY idx_qc_inspected_by (inspectedBy),

    CONSTRAINT fk_qc_grn_item
        FOREIGN KEY (goodsReceiptItemId)
        REFERENCES goods_receipt_items(id)
        ON DELETE CASCADE,

    CONSTRAINT fk_qc_inspected_by
        FOREIGN KEY (inspectedBy)
        REFERENCES users(id)

) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4
COLLATE=utf8mb4_unicode_ci;


SET FOREIGN_KEY_CHECKS = 1;
