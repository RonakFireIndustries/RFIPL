-- ============================================================
-- RFIPL INVENTORY - FINISHED GOODS & PRODUCTION
-- MySQL 5.7+ (compatible with 5.7.23)
-- ------------------------------------------------------------
-- Step 4 of the inventory rebuild. Creates only:
--   1. finished_products
--   2. bills_of_materials
--   3. bom_items
--   4. production_orders
--   5. production_consumptions
--   6. production_wastage
--   7. finished_product_batches
--   8. production_outputs
--   9. finished_product_stock
--  10. finished_product_stock_ledger
--
-- Depends on (already created):
--   HRMS: users, departments
--   Inventory: inventory_units, inventory_categories, raw_materials,
--              raw_material_batches, raw_material_stock,
--              raw_material_stock_ledger
--
-- DESIGN NOTES
--   * Single store: no stock_locations table and no locationId anywhere.
--   * Actor columns (createdBy, consumedBy, recordedBy) reference
--     users(id), not employees(id), so the admin account can act.
--   * SKU / document numbers are generated by the backend and may be
--     overridden manually where the field is user-facing:
--       FG-0001 (finished products), BOM-0001 (BOMs), PROD-0001 (orders).
--   * Selling price and manual cost stay editable.
--   * Every finished-goods stock row has a batch (batchId NOT NULL).
--   * One active BOM version per product; the backend deactivates older
--     versions when a new version is created.
--   * Completing a production order consumes BOM raw materials FIFO from
--     batch stock, writes raw-material ledger rows, creates a finished
--     batch + stock row and writes a finished-goods ledger row.
--   * No seed rows.
--
-- Usage (phpMyAdmin: Import) or:
--   mysql -h <host> -u <user> -p <database> < inventory_finished_goods_production.sql
-- ============================================================

SET FOREIGN_KEY_CHECKS = 0;


-- ============================================================
-- 1. FINISHED PRODUCTS
-- ============================================================

CREATE TABLE IF NOT EXISTS finished_products (
    id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,

    -- Backend-generated: FG-0001, FG-0002, ... (manual override allowed)
    sku VARCHAR(100) NOT NULL,

    name VARCHAR(200) NOT NULL,
    categoryId BIGINT UNSIGNED NULL,
    unitId BIGINT UNSIGNED NOT NULL,

    description TEXT NULL,

    minimumStockLevel DECIMAL(18,4) NOT NULL DEFAULT 0,

    -- Entered manually; used only as a reference for sales/margin reports
    sellingPrice DECIMAL(14,2) NULL,

    isActive TINYINT(1) NOT NULL DEFAULT 1,

    createdAt TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updatedAt TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
        ON UPDATE CURRENT_TIMESTAMP,
    deletedAt DATETIME NULL,

    PRIMARY KEY (id),

    UNIQUE KEY uq_finished_product_sku (sku),

    KEY idx_finished_product_category (categoryId),

    CONSTRAINT fk_finished_product_category
        FOREIGN KEY (categoryId)
        REFERENCES inventory_categories(id)
        ON DELETE SET NULL,

    CONSTRAINT fk_finished_product_unit
        FOREIGN KEY (unitId)
        REFERENCES inventory_units(id)

) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4
COLLATE=utf8mb4_unicode_ci;


-- ============================================================
-- 2. BILLS OF MATERIALS
-- One active version per finished product (enforced in the API).
-- ============================================================

CREATE TABLE IF NOT EXISTS bills_of_materials (
    id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,

    -- Backend-generated: BOM-0001, BOM-0002, ...
    bomNumber VARCHAR(50) NOT NULL,

    finishedProductId BIGINT UNSIGNED NOT NULL,

    name VARCHAR(200) NOT NULL,

    outputQuantity DECIMAL(18,4) NOT NULL DEFAULT 1,
    outputUnitId BIGINT UNSIGNED NOT NULL,

    versionNumber INT UNSIGNED NOT NULL DEFAULT 1,
    isActive TINYINT(1) NOT NULL DEFAULT 1,

    createdAt TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updatedAt TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
        ON UPDATE CURRENT_TIMESTAMP,
    deletedAt DATETIME NULL,

    PRIMARY KEY (id),

    UNIQUE KEY uq_bom_number (bomNumber),

    KEY idx_bom_product (finishedProductId),
    KEY idx_bom_product_active (finishedProductId, isActive),

    CONSTRAINT fk_bom_finished_product
        FOREIGN KEY (finishedProductId)
        REFERENCES finished_products(id),

    CONSTRAINT fk_bom_output_unit
        FOREIGN KEY (outputUnitId)
        REFERENCES inventory_units(id)

) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4
COLLATE=utf8mb4_unicode_ci;


-- ============================================================
-- 3. BOM ITEMS
-- ============================================================

CREATE TABLE IF NOT EXISTS bom_items (
    id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,

    bomId BIGINT UNSIGNED NOT NULL,
    rawMaterialId BIGINT UNSIGNED NOT NULL,

    requiredQuantity DECIMAL(18,4) NOT NULL,
    unitId BIGINT UNSIGNED NOT NULL,

    -- Applied to the required quantity when production is completed
    wastagePercentage DECIMAL(8,4) NOT NULL DEFAULT 0,

    PRIMARY KEY (id),

    UNIQUE KEY uq_bom_material (bomId, rawMaterialId),

    CONSTRAINT fk_bom_item_bom
        FOREIGN KEY (bomId)
        REFERENCES bills_of_materials(id)
        ON DELETE CASCADE,

    CONSTRAINT fk_bom_item_material
        FOREIGN KEY (rawMaterialId)
        REFERENCES raw_materials(id),

    CONSTRAINT fk_bom_item_unit
        FOREIGN KEY (unitId)
        REFERENCES inventory_units(id)

) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4
COLLATE=utf8mb4_unicode_ci;


-- ============================================================
-- 4. PRODUCTION ORDERS
-- ============================================================

CREATE TABLE IF NOT EXISTS production_orders (
    id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,

    -- Backend-generated: PROD-0001, PROD-0002, ...
    productionNumber VARCHAR(50) NOT NULL,

    departmentId BIGINT UNSIGNED NULL,
    bomId BIGINT UNSIGNED NULL,

    plannedStartDate DATE NULL,
    plannedCompletionDate DATE NULL,

    actualStartAt DATETIME NULL,
    actualCompletedAt DATETIME NULL,

    status ENUM(
        'draft',
        'planned',
        'in_progress',
        'completed',
        'cancelled'
    ) NOT NULL DEFAULT 'draft',

    -- users(id)
    createdBy BIGINT UNSIGNED NOT NULL,

    remarks TEXT NULL,

    createdAt TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updatedAt TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
        ON UPDATE CURRENT_TIMESTAMP,

    PRIMARY KEY (id),

    UNIQUE KEY uq_production_number (productionNumber),

    KEY idx_production_status (status),
    KEY idx_production_bom (bomId),

    CONSTRAINT fk_production_department
        FOREIGN KEY (departmentId)
        REFERENCES departments(id)
        ON DELETE SET NULL,

    CONSTRAINT fk_production_bom
        FOREIGN KEY (bomId)
        REFERENCES bills_of_materials(id)
        ON DELETE SET NULL,

    CONSTRAINT fk_production_created_by
        FOREIGN KEY (createdBy)
        REFERENCES users(id)

) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4
COLLATE=utf8mb4_unicode_ci;


-- ============================================================
-- 5. PRODUCTION MATERIAL CONSUMPTION
-- Single store: no locationId.
-- ============================================================

CREATE TABLE IF NOT EXISTS production_consumptions (
    id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,

    productionOrderId BIGINT UNSIGNED NOT NULL,
    rawMaterialId BIGINT UNSIGNED NOT NULL,

    batchId BIGINT UNSIGNED NULL,

    consumptionMode ENUM('automatic', 'manual') NOT NULL,

    plannedQuantity DECIMAL(18,4) NULL,
    consumedQuantity DECIMAL(18,4) NOT NULL,

    unitId BIGINT UNSIGNED NOT NULL,

    -- users(id)
    consumedBy BIGINT UNSIGNED NULL,
    consumedAt DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,

    remarks TEXT NULL,

    PRIMARY KEY (id),

    KEY idx_consumption_order (productionOrderId),
    KEY idx_consumption_material (rawMaterialId),

    CONSTRAINT fk_consumption_production
        FOREIGN KEY (productionOrderId)
        REFERENCES production_orders(id)
        ON DELETE CASCADE,

    CONSTRAINT fk_consumption_material
        FOREIGN KEY (rawMaterialId)
        REFERENCES raw_materials(id),

    CONSTRAINT fk_consumption_batch
        FOREIGN KEY (batchId)
        REFERENCES raw_material_batches(id)
        ON DELETE SET NULL,

    CONSTRAINT fk_consumption_unit
        FOREIGN KEY (unitId)
        REFERENCES inventory_units(id),

    CONSTRAINT fk_consumption_user
        FOREIGN KEY (consumedBy)
        REFERENCES users(id)
        ON DELETE SET NULL

) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4
COLLATE=utf8mb4_unicode_ci;


-- ============================================================
-- 6. PRODUCTION WASTAGE
-- ============================================================

CREATE TABLE IF NOT EXISTS production_wastage (
    id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,

    productionOrderId BIGINT UNSIGNED NOT NULL,
    rawMaterialId BIGINT UNSIGNED NULL,

    wastageType ENUM('normal', 'excess', 'damaged', 'scrap') NOT NULL,

    quantity DECIMAL(18,4) NOT NULL,
    unitId BIGINT UNSIGNED NOT NULL,

    description TEXT NULL,

    -- users(id)
    recordedBy BIGINT UNSIGNED NULL,
    recordedAt DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,

    PRIMARY KEY (id),

    KEY idx_wastage_order (productionOrderId),

    CONSTRAINT fk_wastage_production
        FOREIGN KEY (productionOrderId)
        REFERENCES production_orders(id)
        ON DELETE CASCADE,

    CONSTRAINT fk_wastage_material
        FOREIGN KEY (rawMaterialId)
        REFERENCES raw_materials(id)
        ON DELETE SET NULL,

    CONSTRAINT fk_wastage_unit
        FOREIGN KEY (unitId)
        REFERENCES inventory_units(id),

    CONSTRAINT fk_wastage_user
        FOREIGN KEY (recordedBy)
        REFERENCES users(id)
        ON DELETE SET NULL

) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4
COLLATE=utf8mb4_unicode_ci;


-- ============================================================
-- 7. FINISHED PRODUCT BATCHES
-- Every finished-goods stock row points to one of these batches.
-- ============================================================

CREATE TABLE IF NOT EXISTS finished_product_batches (
    id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,

    finishedProductId BIGINT UNSIGNED NOT NULL,
    batchNumber VARCHAR(100) NOT NULL,

    productionOrderId BIGINT UNSIGNED NULL,

    manufacturingDate DATE NOT NULL,

    originalQuantity DECIMAL(18,4) NOT NULL,
    currentQuantity DECIMAL(18,4) NOT NULL,

    unitId BIGINT UNSIGNED NOT NULL,

    -- Entered manually; may be left blank
    manualCost DECIMAL(14,2) NULL,

    createdAt TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,

    PRIMARY KEY (id),

    UNIQUE KEY uq_finished_batch_number (batchNumber),

    KEY idx_finished_batch_product (finishedProductId),

    CONSTRAINT fk_finished_batch_product
        FOREIGN KEY (finishedProductId)
        REFERENCES finished_products(id),

    CONSTRAINT fk_finished_batch_production
        FOREIGN KEY (productionOrderId)
        REFERENCES production_orders(id)
        ON DELETE SET NULL,

    CONSTRAINT fk_finished_batch_unit
        FOREIGN KEY (unitId)
        REFERENCES inventory_units(id)

) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4
COLLATE=utf8mb4_unicode_ci;


-- ============================================================
-- 8. PRODUCTION OUTPUT
-- Created automatically when a production order is completed.
-- Supports multiple finished products per order.
-- ============================================================

CREATE TABLE IF NOT EXISTS production_outputs (
    id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,

    productionOrderId BIGINT UNSIGNED NOT NULL,
    finishedProductId BIGINT UNSIGNED NOT NULL,

    -- Finished stock is batch-tracked, so output always has a batch
    batchId BIGINT UNSIGNED NOT NULL,

    outputQuantity DECIMAL(18,4) NOT NULL,
    unitId BIGINT UNSIGNED NOT NULL,

    manufacturingDate DATE NOT NULL,

    createdAt TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,

    PRIMARY KEY (id),

    KEY idx_output_order (productionOrderId),

    CONSTRAINT fk_output_production
        FOREIGN KEY (productionOrderId)
        REFERENCES production_orders(id)
        ON DELETE CASCADE,

    CONSTRAINT fk_output_product
        FOREIGN KEY (finishedProductId)
        REFERENCES finished_products(id),

    CONSTRAINT fk_output_batch
        FOREIGN KEY (batchId)
        REFERENCES finished_product_batches(id),

    CONSTRAINT fk_output_unit
        FOREIGN KEY (unitId)
        REFERENCES inventory_units(id)

) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4
COLLATE=utf8mb4_unicode_ci;


-- ============================================================
-- 9. FINISHED PRODUCT STOCK
-- Single store: one row per product + batch. batchId is NOT NULL.
-- ============================================================

CREATE TABLE IF NOT EXISTS finished_product_stock (
    id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,

    finishedProductId BIGINT UNSIGNED NOT NULL,
    batchId BIGINT UNSIGNED NOT NULL,

    quantity DECIMAL(18,4) NOT NULL DEFAULT 0,
    unitId BIGINT UNSIGNED NOT NULL,

    updatedAt TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
        ON UPDATE CURRENT_TIMESTAMP,

    PRIMARY KEY (id),

    UNIQUE KEY uq_finished_stock (finishedProductId, batchId),

    CONSTRAINT fk_finished_stock_product
        FOREIGN KEY (finishedProductId)
        REFERENCES finished_products(id),

    CONSTRAINT fk_finished_stock_batch
        FOREIGN KEY (batchId)
        REFERENCES finished_product_batches(id),

    CONSTRAINT fk_finished_stock_unit
        FOREIGN KEY (unitId)
        REFERENCES inventory_units(id)

) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4
COLLATE=utf8mb4_unicode_ci;


-- ============================================================
-- 10. FINISHED PRODUCT STOCK LEDGER
-- Every finished-goods movement, in or out, with user and timestamp.
-- ============================================================

CREATE TABLE IF NOT EXISTS finished_product_stock_ledger (
    id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,

    finishedProductId BIGINT UNSIGNED NOT NULL,
    batchId BIGINT UNSIGNED NOT NULL,

    transactionType ENUM(
        'production_output',
        'transfer_out',
        'transfer_in',
        'dispatch',
        'customer_return',
        'adjustment',
        'damage',
        'loss'
    ) NOT NULL,

    referenceType VARCHAR(100) NULL,
    referenceId BIGINT UNSIGNED NULL,

    quantityIn DECIMAL(18,4) NOT NULL DEFAULT 0,
    quantityOut DECIMAL(18,4) NOT NULL DEFAULT 0,

    unitCost DECIMAL(14,2) NULL,

    remarks TEXT NULL,

    -- users(id)
    createdBy BIGINT UNSIGNED NULL,
    transactionAt DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,

    PRIMARY KEY (id),

    KEY idx_finished_ledger (finishedProductId, transactionAt),
    KEY idx_finished_ledger_batch (batchId),

    CONSTRAINT fk_finished_ledger_product
        FOREIGN KEY (finishedProductId)
        REFERENCES finished_products(id),

    CONSTRAINT fk_finished_ledger_batch
        FOREIGN KEY (batchId)
        REFERENCES finished_product_batches(id),

    CONSTRAINT fk_finished_ledger_user
        FOREIGN KEY (createdBy)
        REFERENCES users(id)
        ON DELETE SET NULL

) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4
COLLATE=utf8mb4_unicode_ci;


SET FOREIGN_KEY_CHECKS = 1;
