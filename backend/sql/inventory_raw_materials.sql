-- ============================================================
-- RFIPL INVENTORY - RAW MATERIAL INVENTORY
-- MySQL 5.7+ (compatible with 5.7.23)
-- ------------------------------------------------------------
-- Step 2 of the inventory rebuild. Creates only:
--   1. raw_materials
--   2. raw_material_suppliers
--   3. raw_material_batches
--   4. raw_material_stock
--   5. raw_material_stock_ledger
--
-- Depends on (already created by inventory_core.sql):
--   inventory_units, inventory_categories, suppliers
-- Also references HRMS users(id) for ledger.createdBy.
--
-- DESIGN NOTES
--   * Single store: no stock_locations table and no locationId.
--   * Stock is tracked per material + batch (batchId NOT NULL).
--   * Batch/lot tracking without expiry dates.
--   * Multiple suppliers per material with price + preferred flag.
--   * Full stock movement ledger.
--   * SKU is generated by the backend (RM-0001...) and may be
--     overridden manually; it stays unique here.
--   * Extra material fields: HSN + GST rate and grade / size /
--     specification / thickness.
--   * No seed rows.
--
-- Usage (phpMyAdmin: Import) or:
--   mysql -h <host> -u <user> -p <database> < inventory_raw_materials.sql
-- ============================================================

SET FOREIGN_KEY_CHECKS = 0;


-- ============================================================
-- 1. RAW MATERIALS
-- ============================================================

CREATE TABLE IF NOT EXISTS raw_materials (
    id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,

    sku VARCHAR(100) NOT NULL,
    name VARCHAR(200) NOT NULL,

    categoryId BIGINT UNSIGNED NULL,
    unitId BIGINT UNSIGNED NOT NULL,

    description TEXT NULL,

    -- Extra attributes for fabrication materials
    grade VARCHAR(100) NULL,
    specification TEXT NULL,
    thickness VARCHAR(50) NULL,
    size VARCHAR(100) NULL,

    -- Purchase tax details
    hsnCode VARCHAR(20) NULL,
    gstRate DECIMAL(5,2) NULL,

    -- Stock control
    minimumStockLevel DECIMAL(18,4) NOT NULL DEFAULT 0,
    reorderLevel DECIMAL(18,4) NOT NULL DEFAULT 0,
    defaultPurchasePrice DECIMAL(14,2) NULL,

    isActive TINYINT(1) NOT NULL DEFAULT 1,

    createdAt TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updatedAt TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
        ON UPDATE CURRENT_TIMESTAMP,
    deletedAt DATETIME NULL,

    PRIMARY KEY (id),

    UNIQUE KEY uq_raw_material_sku (sku),

    KEY idx_raw_material_category (categoryId),
    KEY idx_raw_material_name (name),

    CONSTRAINT fk_raw_material_category
        FOREIGN KEY (categoryId)
        REFERENCES inventory_categories(id)
        ON DELETE SET NULL,

    CONSTRAINT fk_raw_material_unit
        FOREIGN KEY (unitId)
        REFERENCES inventory_units(id)

) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4
COLLATE=utf8mb4_unicode_ci;


-- ============================================================
-- 2. RAW MATERIAL SUPPLIERS
-- Multiple suppliers per material with price and preferred flag
-- ============================================================

CREATE TABLE IF NOT EXISTS raw_material_suppliers (
    id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,

    rawMaterialId BIGINT UNSIGNED NOT NULL,
    supplierId BIGINT UNSIGNED NOT NULL,

    supplierItemCode VARCHAR(100) NULL,
    purchasePrice DECIMAL(14,2) NULL,
    isPreferred TINYINT(1) NOT NULL DEFAULT 0,

    createdAt TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updatedAt TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
        ON UPDATE CURRENT_TIMESTAMP,

    PRIMARY KEY (id),

    UNIQUE KEY uq_material_supplier (
        rawMaterialId,
        supplierId
    ),

    KEY idx_material_supplier_supplier (supplierId),

    CONSTRAINT fk_material_supplier_material
        FOREIGN KEY (rawMaterialId)
        REFERENCES raw_materials(id)
        ON DELETE CASCADE,

    CONSTRAINT fk_material_supplier_supplier
        FOREIGN KEY (supplierId)
        REFERENCES suppliers(id)
        ON DELETE CASCADE

) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4
COLLATE=utf8mb4_unicode_ci;


-- ============================================================
-- 3. RAW MATERIAL BATCHES
-- Batch/lot tracking, no expiry date
-- ============================================================

CREATE TABLE IF NOT EXISTS raw_material_batches (
    id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,

    rawMaterialId BIGINT UNSIGNED NOT NULL,
    supplierId BIGINT UNSIGNED NULL,

    batchNumber VARCHAR(100) NOT NULL,
    receivedDate DATE NOT NULL,

    purchasePrice DECIMAL(14,2) NOT NULL,
    originalQuantity DECIMAL(18,4) NOT NULL,
    currentQuantity DECIMAL(18,4) NOT NULL,

    unitId BIGINT UNSIGNED NOT NULL,

    qcStatus ENUM(
        'approved',
        'rejected',
        'partial'
    ) NOT NULL DEFAULT 'approved',

    createdAt TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updatedAt TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
        ON UPDATE CURRENT_TIMESTAMP,

    PRIMARY KEY (id),

    UNIQUE KEY uq_raw_material_batch (
        rawMaterialId,
        batchNumber
    ),

    KEY idx_raw_batch_supplier (supplierId),

    CONSTRAINT fk_raw_batch_material
        FOREIGN KEY (rawMaterialId)
        REFERENCES raw_materials(id),

    CONSTRAINT fk_raw_batch_supplier
        FOREIGN KEY (supplierId)
        REFERENCES suppliers(id)
        ON DELETE SET NULL,

    CONSTRAINT fk_raw_batch_unit
        FOREIGN KEY (unitId)
        REFERENCES inventory_units(id)

) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4
COLLATE=utf8mb4_unicode_ci;


-- ============================================================
-- 4. RAW MATERIAL STOCK
-- Single store: one quantity per material + batch.
-- batchId is NOT NULL so every stock row is traceable.
-- ============================================================

CREATE TABLE IF NOT EXISTS raw_material_stock (
    id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,

    rawMaterialId BIGINT UNSIGNED NOT NULL,
    batchId BIGINT UNSIGNED NOT NULL,

    quantity DECIMAL(18,4) NOT NULL DEFAULT 0,
    unitId BIGINT UNSIGNED NOT NULL,

    updatedAt TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
        ON UPDATE CURRENT_TIMESTAMP,

    PRIMARY KEY (id),

    UNIQUE KEY uq_raw_stock (
        rawMaterialId,
        batchId
    ),

    CONSTRAINT fk_raw_stock_material
        FOREIGN KEY (rawMaterialId)
        REFERENCES raw_materials(id),

    CONSTRAINT fk_raw_stock_batch
        FOREIGN KEY (batchId)
        REFERENCES raw_material_batches(id)
        ON DELETE CASCADE,

    CONSTRAINT fk_raw_stock_unit
        FOREIGN KEY (unitId)
        REFERENCES inventory_units(id)

) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4
COLLATE=utf8mb4_unicode_ci;


-- ============================================================
-- 5. RAW MATERIAL STOCK LEDGER
-- Every stock movement, in or out, with user and timestamp.
-- ============================================================

CREATE TABLE IF NOT EXISTS raw_material_stock_ledger (
    id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,

    rawMaterialId BIGINT UNSIGNED NOT NULL,
    batchId BIGINT UNSIGNED NULL,

    transactionType ENUM(
        'opening_stock',
        'purchase_receipt',
        'qc_approved',
        'qc_rejected',
        'production_consumption',
        'transfer_out',
        'transfer_in',
        'adjustment',
        'damage',
        'loss',
        'return_supplier'
    ) NOT NULL,

    referenceType VARCHAR(100) NULL,
    referenceId BIGINT UNSIGNED NULL,

    quantityIn DECIMAL(18,4) NOT NULL DEFAULT 0,
    quantityOut DECIMAL(18,4) NOT NULL DEFAULT 0,

    unitCost DECIMAL(14,2) NULL,

    remarks TEXT NULL,

    createdBy BIGINT UNSIGNED NULL,
    transactionAt DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,

    PRIMARY KEY (id),

    KEY idx_raw_material_ledger (
        rawMaterialId,
        transactionAt
    ),

    KEY idx_raw_material_ledger_batch (batchId),

    CONSTRAINT fk_raw_ledger_material
        FOREIGN KEY (rawMaterialId)
        REFERENCES raw_materials(id),

    CONSTRAINT fk_raw_ledger_batch
        FOREIGN KEY (batchId)
        REFERENCES raw_material_batches(id)
        ON DELETE SET NULL,

    CONSTRAINT fk_raw_ledger_user
        FOREIGN KEY (createdBy)
        REFERENCES users(id)
        ON DELETE SET NULL

) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4
COLLATE=utf8mb4_unicode_ci;


SET FOREIGN_KEY_CHECKS = 1;
